#!/usr/bin/env python3
"""Generate the Nigeria lock-screen artwork in the style of the omarchy.org hero.

  lock-emblem.svg  The Omarchy pixel wordmark, rebuilt pixel by pixel: OM and CHY
                   in a green ramp, AR in a white ramp (the flag, left to right),
                   each shaded light-to-dark in five clean horizontal bands,
                   like the homepage logo.
  lock-pixels.svg  A field of scattered pixel squares, dense at the edges and
                   clear in the middle, in the theme's greens and whites.
  lock-glow.svg    A soft centre shade so the wordmark sits in the photo
                   without a card behind it.

Usage: make-lock-art.py <output-dir>
Requires ImageMagick (`magick`) to read Omarchy's logo.svg into a pixel grid.
"""
import random
import subprocess
import sys
from pathlib import Path

LOGO = "/usr/share/omarchy/logo.svg"
COLS, ROWS, CELL = 81, 19, 15            # the wordmark's native pixel grid
BAND_EDGES = (27, 49)                    # column gaps after "OM" and after "AR"

# Light (top) to dark (bottom), five clean bands each, like the homepage wordmark.
GREEN = ["#BDF3D5", "#8CE3B4", "#5BCD93", "#3AA874", "#287A56"]
WHITE = ["#FFFFFF", "#E5EEE9", "#C6D5CC", "#A2B6AB", "#7E9488"]


def logo_grid() -> set[tuple[int, int]]:
    out = subprocess.run(
        ["magick", "-background", "none", "-density", "72", LOGO, "-alpha", "extract",
         "-filter", "point", "-resize", f"{COLS}x{ROWS}!", "-threshold", "50%", "txt:-"],
        check=True, capture_output=True, text=True,
    ).stdout
    ink = set()
    for line in out.splitlines()[1:]:
        coords, _, rest = line.partition(":")
        if "#FFFFFF" in rest or "white" in rest:
            x, y = (int(v) for v in coords.split(","))
            ink.add((x, y))
    return ink


def emblem(rng: random.Random) -> str:
    rects = []
    for x, y in sorted(logo_grid()):
        ramp = WHITE if BAND_EDGES[0] <= x < BAND_EDGES[1] else GREEN
        band = min(len(ramp) - 1, y * len(ramp) // ROWS)
        rects.append(f'<rect x="{x * CELL}" y="{y * CELL}" width="{CELL}" height="{CELL}" fill="{ramp[band]}"/>')
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {COLS * CELL} {ROWS * CELL}" '
        f'width="{COLS * CELL}" height="{ROWS * CELL}" shape-rendering="crispEdges">\n'
        "<!-- Omarchy wordmark in Nigeria's green-white-green, omarchy.org style. Generated by extras/make-lock-art.py -->\n"
        + "\n".join(rects) + "\n</svg>\n"
    )


def pixel_field(rng: random.Random) -> str:
    w, h, cell = 2560, 1080, 14                       # wide enough for 21:9; cropped on 16:9
    cols, rows = w // cell, h // cell
    # Dim and quiet, like the homepage: the twinkles are added live by the lock.
    colours = ["#24402F", "#2C4A3B", "#355A47", "#3F6B53", "#1F3528"]
    rects = []
    for cy in range(rows):
        for cx in range(cols):
            # 0 at the centre, 1 at the edges (elliptical).
            dx = (cx + 0.5) / cols * 2 - 1
            dy = (cy + 0.5) / rows * 2 - 1
            d = max(abs(dx) ** 1.6, abs(dy) ** 1.6) ** (1 / 1.6)
            p = max(0.0, d - 0.55) ** 2 * 1.6
            if rng.random() < p:
                colour = rng.choices(colours, weights=(4, 5, 3, 1, 3))[0]
                opacity = round(rng.uniform(0.55, 0.95), 2)
                size = cell - 4
                rects.append(f'<rect x="{cx * cell + 2}" y="{cy * cell + 2}" width="{size}" height="{size}" fill="{colour}" opacity="{opacity}"/>')
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" shape-rendering="crispEdges">\n'
        "<!-- Scattered pixel field for the Nigeria lock screen. Generated by extras/make-lock-art.py -->\n"
        + "\n".join(rects) + "\n</svg>\n"
    )


def glow() -> str:
    # A soft dark-green pool of shade behind the wordmark and field, fading to
    # nothing: it keeps them readable on bright photos without a visible box.
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" width="1600" height="900" preserveAspectRatio="none">\n'
        "<!-- Centre shade for the Nigeria lock screen. Generated by extras/make-lock-art.py -->\n"
        '<defs><radialGradient id="g" cx="50%" cy="50%" r="50%">'
        '<stop offset="0" stop-color="#0F1A15" stop-opacity="0.82"/>'
        '<stop offset="0.35" stop-color="#0F1A15" stop-opacity="0.70"/>'
        '<stop offset="0.65" stop-color="#0F1A15" stop-opacity="0.30"/>'
        '<stop offset="1" stop-color="#0F1A15" stop-opacity="0"/>'
        "</radialGradient></defs>\n"
        '<rect width="1600" height="900" fill="url(#g)"/>\n</svg>\n'
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    out = Path(sys.argv[1])
    rng = random.Random(1960)                         # fixed seed: same art every run
    (out / "lock-emblem.svg").write_text(emblem(rng))
    (out / "lock-pixels.svg").write_text(pixel_field(rng))
    (out / "lock-glow.svg").write_text(glow())
    print(f"Wrote lock-emblem.svg, lock-pixels.svg and lock-glow.svg to {out}")


if __name__ == "__main__":
    main()
